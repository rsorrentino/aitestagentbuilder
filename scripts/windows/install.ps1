<#
.SYNOPSIS
  Installs AI Test Agent Builder on Windows (Windows Server 2019/2022/2025, Windows 10/11) without Docker.

.DESCRIPTION
  - checks Node.js (20.19+) and the PostgreSQL connection
  - creates .env at the repository root (only if missing) with generated secrets
    and restricts it to Administrators, SYSTEM and the installing user
  - installs dependencies, downloads Chromium into a shared folder usable by a
    Windows service account, builds backend and frontend, runs DB migrations

  Run from an elevated PowerShell prompt:
    powershell -ExecutionPolicy Bypass -File scripts\windows\install.ps1 -PublicHost atab.contoso.local

.PARAMETER PublicHost
  Host name users and CI type in the browser (default: this computer's name).
.PARAMETER ApiPort / UiPort
  Ports of the API (3000) and the web UI (4000).
.PARAMETER DatabaseUrl
  postgresql://user:password@host:5432/aitestagentbuilder (default: local PostgreSQL, user postgres).
.PARAMETER AdminEmail
  First administrator account. A random password is generated and printed once.
.PARAMETER SkipBuild
  Only (re)create configuration, do not install or build.
#>
[CmdletBinding()]
param(
  [string]$PublicHost = $env:COMPUTERNAME.ToLower(),
  [int]$ApiPort = 3000,
  [int]$UiPort = 4000,
  [string]$DatabaseUrl = '',
  [string]$AdminEmail = 'admin@example.com',
  [switch]$NoAuth,
  [switch]$SkipBuild
)

$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$EnvFile = Join-Path $Root '.env'
$Browsers = Join-Path $Root '.playwright-browsers'

function Step($msg) { Write-Host "==> $msg" -ForegroundColor Cyan }
function Fail($msg) { Write-Host "ERROR: $msg" -ForegroundColor Red; exit 1 }
function Invoke-Checked([string]$what, [scriptblock]$cmd) {
  & $cmd
  if ($LASTEXITCODE -ne 0) { Fail "$what failed (exit code $LASTEXITCODE)" }
}
function New-Secret([int]$bytes = 32) {
  $buf = New-Object byte[] $bytes
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buf)
  return [Convert]::ToBase64String($buf)
}
function New-Password {
  # Satisfies the password policy: 20 chars, upper, lower, digit, symbol.
  $chars = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
  $buf = New-Object byte[] 16
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buf)
  $core = -join ($buf | ForEach-Object { $chars[$_ % $chars.Length] })
  return "Aa1!$core"
}

# --- Node.js ---------------------------------------------------------------
Step 'Checking Node.js'
$node = Get-Command node -ErrorAction SilentlyContinue
if (-not $node) { Fail 'Node.js 20.19+ (22 LTS recommended) is required: https://nodejs.org (Windows Installer .msi)' }
$ver = [version]((& node -p "process.versions.node").Trim())
if ($ver -lt [version]'20.19.0') { Fail "Node.js 20.19+ is required (found $ver)" }
Write-Host "    Node.js $ver at $($node.Source)"

# --- .env --------------------------------------------------------------------
if (-not $DatabaseUrl) { $DatabaseUrl = 'postgresql://postgres:postgres@localhost:5432/aitestagentbuilder' }
$apiUrl = "http://${PublicHost}:$ApiPort/api/v1"
$wsUrl = "http://${PublicHost}:$ApiPort"
$uiUrl = "http://${PublicHost}:$UiPort"

if (Test-Path $EnvFile) {
  Step ".env exists - keeping it ($EnvFile)"
} else {
  Step "Creating $EnvFile"
  $adminPassword = New-Password
  $authEnabled = if ($NoAuth) { 'false' } else { 'true' }
  @"
# AI Test Agent Builder - generated by scripts\windows\install.ps1 on $(Get-Date -Format s)
NODE_ENV=production
PORT=$ApiPort
DATABASE_URL=$DatabaseUrl

AUTH_ENABLED=$authEnabled
JWT_SECRET=$(New-Secret 48)
# Keep this key: without it stored credentials (agent secrets, Salesforce personas) cannot be decrypted.
SECRETS_ENCRYPTION_KEY=$(New-Secret 32)
ADMIN_EMAIL=$AdminEmail
ADMIN_PASSWORD=$adminPassword

# Browsers are kept inside the installation so a service account can use them.
PLAYWRIGHT_BROWSERS_PATH=$Browsers
CORS_ORIGIN=$uiUrl,http://localhost:$UiPort
LOG_TO_FILE=true

# Used when building the web UI (compiled into the browser bundle)
NEXT_PUBLIC_API_URL=$apiUrl
NEXT_PUBLIC_WS_URL=$wsUrl

# AI providers (optional) - e.g.
# ANTHROPIC_API_KEY=
# OPENAI_API_KEY=
# COPILOT_MODE=api
# GITHUB_TOKEN=
"@ | Set-Content -Path $EnvFile -Encoding UTF8

  # Only Administrators, SYSTEM and the current user may read the secrets.
  & icacls $EnvFile /inheritance:r /grant:r '*S-1-5-32-544:F' '*S-1-5-18:F' "${env:USERNAME}:F" | Out-Null
  if ($LASTEXITCODE -ne 0) { Write-Warning 'Could not restrict access to .env - restrict it manually to administrators and the service account' }

  Write-Host ''
  Write-Host "    Administrator: $AdminEmail" -ForegroundColor Yellow
  Write-Host "    Password:      $adminPassword   (shown once - change it after the first login)" -ForegroundColor Yellow
  Write-Host ''
}

# Values the build needs from .env
$envValues = @{}
Get-Content $EnvFile | Where-Object { $_ -match '^\s*([A-Z0-9_]+)\s*=\s*(.*)$' } | ForEach-Object {
  $envValues[$Matches[1]] = $Matches[2].Trim()
}
if ($envValues.ContainsKey('PLAYWRIGHT_BROWSERS_PATH')) { $Browsers = $envValues['PLAYWRIGHT_BROWSERS_PATH'] }
if ($envValues.ContainsKey('NEXT_PUBLIC_API_URL')) { $apiUrl = $envValues['NEXT_PUBLIC_API_URL'] }
if ($envValues.ContainsKey('NEXT_PUBLIC_WS_URL')) { $wsUrl = $envValues['NEXT_PUBLIC_WS_URL'] }

if ($SkipBuild) { Step 'Configuration done (-SkipBuild)'; exit 0 }

# --- Backend -----------------------------------------------------------------
Step 'Installing backend dependencies'
Push-Location (Join-Path $Root 'backend')
try {
  Invoke-Checked 'npm ci (backend)' { npm ci --no-audit --no-fund }
  Step "Downloading Chromium into $Browsers"
  $env:PLAYWRIGHT_BROWSERS_PATH = $Browsers
  Invoke-Checked 'playwright install' { npx playwright install chromium }
  Step 'Building backend'
  Invoke-Checked 'backend build' { npm run build }
  Step 'Migrating the database'
  Invoke-Checked 'database migration (is PostgreSQL running and DATABASE_URL correct?)' { node dist/infra/db/migrate.js }
} finally { Pop-Location }

# --- Frontend ----------------------------------------------------------------
Step "Building the web UI (API: $apiUrl)"
Push-Location (Join-Path $Root 'frontend')
try {
  Invoke-Checked 'npm ci (frontend)' { npm ci --no-audit --no-fund }
  $env:NEXT_PUBLIC_API_URL = $apiUrl
  $env:NEXT_PUBLIC_WS_URL = $wsUrl
  $env:NEXT_TELEMETRY_DISABLED = '1'
  Invoke-Checked 'frontend build' { npm run build }
} finally { Pop-Location }

Write-Host ''
Write-Host 'Installed.' -ForegroundColor Green
Write-Host "  Start now:            powershell -File scripts\windows\start.ps1"
Write-Host "  Run as services:      powershell -File scripts\windows\install-service.ps1   (elevated)"
Write-Host "  Open the firewall:    New-NetFirewallRule -DisplayName 'ATAB' -Direction Inbound -Protocol TCP -LocalPort $ApiPort,$UiPort -Action Allow"
Write-Host "  Then browse to:       http://${PublicHost}:$UiPort"
