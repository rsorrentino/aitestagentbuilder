/**
 * Test Data Controller (project-scoped named data sets).
 */

import { Response } from 'express';
import { AuthenticatedRequest } from '../../infra/auth/auth.middleware.js';
import { TestDataRepository } from '../../core/repositories/test-data.repository.js';
import { aiRows, clampCount, datasetRows, describeKinds, generateRows, LOCALE_RE } from '../../modules/quality/test-data-gen.js';

export class TestDataController {
  private repo = new TestDataRepository();

  async createTestData(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const { name, description, tags, environment } = req.body ?? {};
      // An array of rows is stored as { rows: [...] } (a data set that drives data-driven tests)
      const data = Array.isArray(req.body?.data) ? { rows: req.body.data } : req.body?.data;
      if (!name || typeof name !== 'string') {
        res.status(400).json({ error: 'name is required' });
        return;
      }
      if (!data || typeof data !== 'object' || Array.isArray(data)) {
        res.status(400).json({ error: 'data must be a JSON object' });
        return;
      }
      const created = await this.repo.create({
        name, description, data, tags, environment, createdBy: req.user?.email, projectId: req.project!.id,
      });
      res.locals.audit = { entityId: created.id, details: { name } };
      res.status(201).json(created);
    } catch (error: any) {
      res.status(500).json({ error: error.message });
    }
  }

  /**
   * Generate rows: with Faker from { fields: { column: kind } }, or with the AI from
   * { prompt: "…" } (fields then name the columns). save: true stores them as a data set.
   */
  async generateTestData(req: AuthenticatedRequest, res: Response): Promise<void> {
    const body = req.body ?? {};
    const count = clampCount(body.count);
    const locale = typeof body.locale === 'string' && body.locale.trim() ? body.locale.trim() : 'en';
    const fields = body.fields && typeof body.fields === 'object' && !Array.isArray(body.fields) ? body.fields as Record<string, string> : undefined;
    const prompt = typeof body.prompt === 'string' ? body.prompt.trim() : '';
    if (!LOCALE_RE.test(locale)) {
      res.status(400).json({ error: 'locale must be like en, en_US, it, de, fr, es, pt_BR' });
      return;
    }
    if (!prompt && !fields) {
      res.status(400).json({ error: 'Give fields ({ column: kind }, generated with Faker) or a prompt (generated by the AI)' });
      return;
    }
    if (body.save && (!body.name || typeof body.name !== 'string')) {
      res.status(400).json({ error: 'name is required to save the data set' });
      return;
    }
    let rows: Array<Record<string, any>>;
    let source: 'faker' | 'ai';
    let provider: string | undefined;
    try {
      if (prompt) {
        ({ rows, provider } = await aiRows(prompt, count, { fields, locale, preferred: typeof body.provider === 'string' ? body.provider : undefined }));
        source = 'ai';
      } else {
        rows = await generateRows(fields!, count, { locale, seed: body.seed });
        source = 'faker';
      }
    } catch (error: any) {
      const userError = /^(fields must|Invalid column|Unknown fake|Unknown test data locale|AI data generation needs|The AI did not return)/.test(error.message);
      res.status(userError ? 400 : 502).json({ error: error.message });
      return;
    }
    try {
      let saved;
      if (body.save) {
        saved = await this.repo.create({
          name: body.name,
          description: typeof body.description === 'string' ? body.description : (prompt || `Generated: ${Object.entries(fields ?? {}).map(([c, k]) => `${c}=${k}`).join(', ')}`).slice(0, 500),
          data: { rows, generated: { source, ...(prompt ? { prompt } : { fields }), locale, at: new Date().toISOString() } },
          tags: Array.isArray(body.tags) ? body.tags : ['generated'],
          environment: typeof body.environment === 'string' && body.environment ? body.environment : undefined,
          createdBy: req.user?.email,
          projectId: req.project!.id,
        });
        res.locals.audit = { entityId: saved.id, details: { name: saved.name, rows: rows.length, source } };
      }
      res.status(saved ? 201 : 200).json({ rows, source, ...(provider ? { provider } : {}), ...(saved ? { saved } : {}) });
    } catch (error: any) {
      res.status(500).json({ error: error.message });
    }
  }

  /** Fake data kinds usable as {{fake.kind}}, with an example in the locale. */
  async fakeKinds(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const locale = typeof req.query.locale === 'string' && req.query.locale ? req.query.locale : 'en';
      res.json(await describeKinds(locale));
    } catch (error: any) {
      res.status(400).json({ error: error.message });
    }
  }

  async getTestData(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const item = await this.repo.findById(req.params.id, req.project!.id);
      if (!item) {
        res.status(404).json({ error: 'Test data not found' });
        return;
      }
      res.json({ ...item, rowCount: datasetRows(item.data).length });
    } catch (error: any) {
      res.status(500).json({ error: error.message });
    }
  }

  async listTestData(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      res.json(await this.repo.findAll(req.project!.id, {
        environment: req.query.environment ? String(req.query.environment) : undefined,
        limit: parseInt(req.query.limit as string) || 100,
        offset: parseInt(req.query.offset as string) || 0,
      }));
    } catch (error: any) {
      res.status(500).json({ error: error.message });
    }
  }

  async updateTestData(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const body = { ...(req.body ?? {}) };
      if (Array.isArray(body.data)) body.data = { rows: body.data };
      if (body.data !== undefined && (!body.data || typeof body.data !== 'object')) {
        res.status(400).json({ error: 'data must be a JSON object or an array of rows' });
        return;
      }
      const updated = await this.repo.update(req.params.id, body, req.project!.id);
      if (!updated) {
        res.status(404).json({ error: 'Test data not found' });
        return;
      }
      res.json(updated);
    } catch (error: any) {
      res.status(500).json({ error: error.message });
    }
  }

  async deleteTestData(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      if (!(await this.repo.delete(req.params.id, req.project!.id))) {
        res.status(404).json({ error: 'Test data not found' });
        return;
      }
      res.status(204).send();
    } catch (error: any) {
      res.status(500).json({ error: error.message });
    }
  }
}
